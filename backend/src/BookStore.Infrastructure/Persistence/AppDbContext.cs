using BookStore.Application.Abstractions;
using BookStore.Domain.Catalog;
using BookStore.Domain.Common;
using BookStore.Domain.Ordering;
using BookStore.Domain.Payments;
using BookStore.Domain.Shipping;
using BookStore.Domain.Shopping;
using BookStore.Infrastructure.Identity;
using BookStore.Infrastructure.Persistence.Configurations;
using Microsoft.AspNetCore.Identity;
using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;

namespace BookStore.Infrastructure.Persistence;

/// <summary>Single DbContext for the app: Identity tables + catalog + carts, orders, payments.</summary>
public sealed class AppDbContext(DbContextOptions<AppDbContext> options)
    : IdentityDbContext<ApplicationUser, IdentityRole<Guid>, Guid>(options), IAppDbContext
{
    public DbSet<Book> Books => Set<Book>();
    public DbSet<Author> Authors => Set<Author>();
    public DbSet<Category> Categories => Set<Category>();
    public DbSet<Wilaya> Wilayas => Set<Wilaya>();
    public DbSet<Cart> Carts => Set<Cart>();
    public DbSet<Order> Orders => Set<Order>();
    public DbSet<PaymentEvent> PaymentEvents => Set<PaymentEvent>();
    public DbSet<Review> Reviews => Set<Review>();
    public DbSet<RefreshToken> RefreshTokens => Set<RefreshToken>();

    /// <summary>
    /// Wraps the work in the retrying execution strategy (EnableRetryOnFailure) and one transaction.
    /// The change tracker is cleared before each attempt so a retry starts from a clean state.
    /// </summary>
    public Task<T> InTransactionAsync<T>(Func<CancellationToken, Task<T>> operation, CancellationToken cancellationToken)
    {
        var strategy = Database.CreateExecutionStrategy();
        return strategy.ExecuteAsync(async ct =>
        {
            ChangeTracker.Clear();
            await using var transaction = await Database.BeginTransactionAsync(ct);
            var result = await operation(ct);
            await transaction.CommitAsync(ct);
            return result;
        }, cancellationToken);
    }

    public void ResetChangeTracker() => ChangeTracker.Clear();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        // Identity's own model first, then our configurations (which may override table names).
        base.OnModelCreating(modelBuilder);
        IdentityTableNames.Apply(modelBuilder);

        // Trigram matching backs the ILIKE '%term%' catalog search (works for Arabic and Latin text).
        modelBuilder.HasPostgresExtension("pg_trgm");

        // Picks up every IEntityTypeConfiguration<T> in Persistence/Configurations.
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(AppDbContext).Assembly);

        // Our entities create their own Guid v7 keys. Telling EF the keys are never generated by the
        // database makes it treat a new child added to a loaded parent (e.g. a CartItem added to an
        // existing Cart) as an INSERT; otherwise a pre-set key looks like an existing row and EF
        // issues an UPDATE that matches nothing.
        foreach (var entityType in modelBuilder.Model.GetEntityTypes()
                     .Where(t => typeof(Entity).IsAssignableFrom(t.ClrType) && !t.IsOwned()))
        {
            modelBuilder.Entity(entityType.ClrType).Property(nameof(Entity.Id)).ValueGeneratedNever();
        }
    }
}

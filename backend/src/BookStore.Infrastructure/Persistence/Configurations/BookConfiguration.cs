using BookStore.Domain.Catalog;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace BookStore.Infrastructure.Persistence.Configurations;

internal sealed class BookConfiguration : IEntityTypeConfiguration<Book>
{
    public void Configure(EntityTypeBuilder<Book> builder)
    {
        builder.Property(b => b.Title).HasMaxLength(300).IsRequired();
        builder.Property(b => b.Slug).HasMaxLength(200).IsRequired();
        builder.Property(b => b.Description).HasMaxLength(5000).IsRequired();
        builder.Property(b => b.Isbn).HasMaxLength(17).IsRequired();
        builder.Property(b => b.Language).HasMaxLength(8).IsRequired();
        builder.Property(b => b.Publisher).HasMaxLength(200).IsRequired();
        builder.Property(b => b.CoverImageUrl).HasMaxLength(1000);

        // Generated by PostgreSQL from price/sale_price; EF never writes it.
        builder.Property(b => b.EffectivePrice)
            .HasComputedColumnSql("COALESCE(sale_price, price)", stored: true);

        builder.HasIndex(b => b.Slug).IsUnique();
        builder.HasIndex(b => b.Isbn).IsUnique();
        builder.HasIndex(b => b.EffectivePrice);
        builder.HasIndex(b => b.PublishedOn);
        builder.HasIndex(b => b.Language);

        // Trigram index for ILIKE '%term%' search on the title.
        builder.HasIndex(b => b.Title)
            .HasMethod("gin")
            .HasOperators("gin_trgm_ops")
            .HasDatabaseName("ix_books_title_trgm");

        builder.ToTable(t =>
        {
            t.HasCheckConstraint("ck_books_price_positive", "price > 0");
            t.HasCheckConstraint("ck_books_sale_price", "sale_price IS NULL OR (sale_price > 0 AND sale_price < price)");
            t.HasCheckConstraint("ck_books_stock_non_negative", "stock >= 0");
            t.HasCheckConstraint("ck_books_page_count", "page_count > 0");
        });

        // Many-to-many join tables: book_authors and book_categories.
        builder.HasMany(b => b.Authors).WithMany(a => a.Books).UsingEntity("book_authors");
        builder.HasMany(b => b.Categories).WithMany(c => c.Books).UsingEntity("book_categories");

        builder.Navigation(b => b.Authors).UsePropertyAccessMode(PropertyAccessMode.Field);
        builder.Navigation(b => b.Categories).UsePropertyAccessMode(PropertyAccessMode.Field);
    }
}
